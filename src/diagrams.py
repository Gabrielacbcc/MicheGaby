from src.profiles import PROFILES, profile_names, profile_vocabulary
from src.stage2_normalization.transducer import transducer_definition
from src.stage3_recognition.automaton import automaton_definition

# Generates the diagrams and definitions for Stages 2 and 3 in Markdown using the project's data. This keeps the documentation consistent with the code.

def _show(char):
    return "space" if char == " " else char


def transducer_markdown(token):
    d = transducer_definition(token)
    lines = [f"#### Transducer for {token}", ""]
    lines.append(f"- Q = {{{', '.join(d['Q'])}}}")
    lines.append(f"- Sigma = {{{', '.join(_show(c) for c in d['Sigma'])}}}")
    lines.append(f"- Gamma = {{{token}}}")
    lines.append(f"- q0 = {d['q0']}")
    lines.append(f"- F = {{{', '.join(d['F'])}}}")
    lines.append("- Transitions and outputs, one row each (epsilon means nothing is printed):")
    lines.append("")
    lines.append("| from | reads | to | prints |")
    lines.append("|------|-------|----|--------|")
    for source, char, target in d["delta"]:
        out = " ".join(d["omega"][(source, char, target)]) or "epsilon"
        lines.append(f"| {source} | {_show(char)} | {target} | {out} |")
    lines.append("")
    lines.append("```mermaid")
    lines.append("stateDiagram-v2")
    lines.append("    direction LR")
    lines.append(f"    [*] --> {d['q0']}")
    for source, char, target in d["delta"]:
        out = " ".join(d["omega"][(source, char, target)]) or "ε"
        lines.append(f"    {source} --> {target}: {_show(char)} / {out}")
    lines.append("    qf --> [*]")
    lines.append("```")
    lines.append("")
    return "\n".join(lines)


def automaton_markdown(profile):
    d = automaton_definition(profile)
    lines = [f"### Automaton for {profile}", ""]
    lines.append("Type: DFA (one transition at most per state and token, no epsilon transitions).")
    lines.append("")
    lines.append(f"- Q = {{{', '.join(d['Q'])}}}")
    lines.append(f"- Sigma = {{{', '.join(d['Sigma'])}}}")
    lines.append(f"- q0 = {d['q0']}")
    lines.append(f"- F = {{{', '.join(d['F'])}}}")
    lines.append("- delta (partial function, a missing transition means reject):")
    lines.append("")
    lines.append("| from | reads | to |")
    lines.append("|------|-------|----|")
    for (source, token), target in d["delta"].items():
        lines.append(f"| {source} | {token} | {target} |")
    lines.append("")
    lines.append("Pattern, in order: " + " -> ".join(
        f"{category} ({' | '.join(tokens)})" for _, category, tokens in PROFILES[profile]
    ))
    lines.append("")
    lines.append("```mermaid")
    lines.append("stateDiagram-v2")
    lines.append("    direction LR")
    lines.append(f"    [*] --> {d['q0']}")
    for (source, token), target in d["delta"].items():
        lines.append(f"    {source} --> {target}: {token}")
    lines.append(f"    {d['F'][0]} --> [*]")
    lines.append("```")
    lines.append("")
    return "\n".join(lines)

# This file lists every transducer used in Stage 2. Each one turns the different spellings of a skill (like \"js\" or \"javascript\") into one 
# standard name (JAVASCRIPT). The transducer of a profile is just these small ones put together, sharing the start state q0. 
# The tables are generated with `python -m src.diagrams` from the same data the programuses, so they always match the code"
def stage2_document():
    parts = ["# Stage 3 automata (generated)", "",
            "Generated by `python -m src.diagrams`.", ""]
    for profile in profile_names():
        parts.append(automaton_markdown(profile))
    return "\n".join(parts)

def stage3_document():
    parts = ["# Stage 3 automata (generated)", "",
             "Generated by `python -m src.diagrams`.", ""]
    for profile in profile_names():
        parts.append(automaton_markdown(profile))
    return "\n".join(parts)

if __name__ == "__main__":
    with open("docs/stage2-transducers.md", "w", encoding="utf-8") as f:
        f.write(stage2_document())
    with open("docs/stage3-automata.md", "w", encoding="utf-8") as f:
        f.write(stage3_document())
    print("Wrote docs/stage2-transducers.md and docs/stage3-automata.md")

